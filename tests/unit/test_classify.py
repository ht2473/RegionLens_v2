class TestSeriesKey:
    """Построение ключа ряда."""

    def test_indicator_without_subsection(self) -> None:
        """Показатель без разрезов получает суффикс 00."""
        assert make_series_key("Y477100001", None) == "Y477100001:00"
        assert make_series_key("Y477100001", "CD") == "Y477100001:00"

    def test_subsection_produces_stable_suffix(self) -> None:
        """Ключ ряда устойчив: одинаковый разрез даёт одинаковый суффикс."""
        first = make_series_key("Y477100001", "Безработные, тыс. человек")
        second = make_series_key("Y477100001", "Безработные,  тыс. человек ")
        assert first == second
        assert first.startswith("Y477100001:")

    def test_different_subsections_produce_different_keys(self) -> None:
        """Разные разрезы одного показателя — разные ряды."""
        first = make_series_key("Y477100001", "Безработные, тыс. человек")
        second = make_series_key("Y477100001", "Уровень безработицы, в %")
        assert first != second
