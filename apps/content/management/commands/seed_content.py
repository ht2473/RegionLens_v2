class Command(BaseCommand):
    """Заполнить разделы методики и глоссарий."""

    help = "Начальное наполнение содержимого: методика и глоссарий"

    def add_arguments(self, parser: CommandParser) -> None:
        """Объявить ключи команды."""
        parser.add_argument(
            "--force",
            action="store_true",
            help="Перезаписать тексты существующих записей (правки редактора будут потеряны)",
        )
        parser.add_argument(
            "--only",
            choices=["methodology", "glossary"],
            help="Заполнить только указанный раздел",
        )

    @transaction.atomic
    def handle(self, *args: Any, **options: Any) -> None:  # noqa: ARG002 — контракт команды
        """Выполнить наполнение выбранных разделов."""
        force: bool = options["force"]
        only: str | None = options.get("only")

        if only in (None, "methodology"):
            created, updated = self.seed_methodology(force=force)
            self.stdout.write(f"Методология: создано {created}, обновлено {updated}")
            # Число удалённых — вместе с переводами: считаются только сами разделы.
            _total, deleted = MethodologySection.objects.filter(code__in=RETIRED_SECTIONS).delete()
            retired = deleted.get(MethodologySection._meta.label, 0)
            if retired:
                self.stdout.write(f"Методология: снято прежних разделов {retired}")

        if only in (None, "glossary"):
            created, updated = self.seed_glossary(force=force)
            self.stdout.write(f"Глоссарий: создано {created}, обновлено {updated}")

        for line in text_rules.report(METHODOLOGY, GLOSSARY):
            self.stdout.write(self.style.WARNING(f"Правила текста — {line}"))

        self.stdout.write(self.style.SUCCESS("Наполнение содержимого завершено"))

    # --- Разделы наполнения ------------------------------------------------------------

    def seed_methodology(self, *, force: bool) -> tuple[int, int]:
        """Создать или обновить разделы методологии."""
        created = updated = 0
        for item in METHODOLOGY:
            section, is_new = MethodologySection.objects.get_or_create(
                code=item["code"],
                defaults={
                    "block": item["block"],
                    "display_order": item["order"],
                    "tool_url_name": item.get("tool_url_name", ""),
                    "references": item.get("references", []),
                },
            )
            if not is_new and not force:
                continue

            section.block = item["block"]
            section.display_order = item["order"]
            section.tool_url_name = item.get("tool_url_name", "")
            section.references = item.get("references", [])
            section.set_current_language("ru")
            section.title = item["title"]
            section.summary = item["summary"]
            section.formula = item.get("formula", "")
            section.limitations = item.get("limitations", "")
            section.body = item["body"]
            section.save()

            created += is_new
            updated += not is_new
        return created, updated

    def seed_glossary(self, *, force: bool) -> tuple[int, int]:
        """Создать или обновить термины глоссария."""
        sections = {section.code: section for section in MethodologySection.objects.all()}
        created = updated = 0

        for item in GLOSSARY:
            term, is_new = GlossaryTerm.objects.get_or_create(
                slug=item["slug"],
                defaults={
                    "category": item["category"],
                },
            )
            if not is_new and not force:
                continue

            term.category = item["category"]
            term.is_published = True
            term.methodology_section = sections.get(item.get("section", ""))
            term.set_current_language("ru")
            term.term = item["term"]
            term.short_definition = item["short"]
            term.definition = item["definition"]
            term.synonyms = item.get("synonyms", "")
            term.save()

            created += is_new
            updated += not is_new
        return created, updated
