#!/usr/bin/env sh
# =====================================================================================
# Точка входа контейнера: подготовка окружения и запуск заданной команды.
#
# Шаги идемпотентны: контейнер перезапускается при каждом обновлении и сбое.
# Миграции — здесь, чтобы после отката на прежний образ приложение не оказалось старше
# схемы. Склад здесь не собирается (минуты): его собирает загрузка набора из панели
# или deploy.sh --with-etl.
# =====================================================================================

set -eu

ROLE="${1:-}"

# --- Ожидание готовности зависимостей --------------------------------------------------
# Проверка состояния в compose не спасает, если база перезапустилась после старта приложения.
wait_for_database() {
    attempt=0
    until python -c "
import sys

import django

django.setup()
from django.db import connection

try:
    connection.ensure_connection()
except Exception as error:
    print(error, file=sys.stderr)
    sys.exit(1)
"; do
        attempt=$((attempt + 1))
        if [ "$attempt" -ge 30 ]; then
            echo "База данных недоступна после 30 попыток, запуск прерван" >&2
            exit 1
        fi
        echo "Ожидание базы данных (попытка $attempt)…"
        sleep 2
    done
}

# --- Подготовка ---------------------------------------------------------------------------
# Миграции и статика — только для веб-процесса; служебные команды в том же образе базу не ждут.
case "$ROLE" in
    gunicorn)
        # Упущения настроек эксплуатации (HTTP без перенаправления, куки без Secure,
        # нет HSTS) прерывают запуск. SKIP_DEPLOY_CHECK=1 — для осознанного отступления
        # (стенд без сертификата, проверка развёртывания).
        if [ "${SKIP_DEPLOY_CHECK:-0}" != "1" ]; then
            echo "Проверка настроек развёртывания…"
            python manage.py check --deploy --fail-level WARNING
        fi
        # Том /app/staticfiles заполняется из образа, только пока пуст, а имена файлов
        # несут отпечаток содержимого: без повторной сборки разметка ссылалась бы
        # на файлы, которых в томе нет. К базе сборка не обращается — идёт до её ожидания.
        echo "Обновление статики…"
        python manage.py collectstatic --noinput

        wait_for_database
        echo "Применение миграций…"
        python manage.py migrate --noinput
        # Справочник территорий — при каждом запуске: без него сборка склада падает,
        # а команда идемпотентна.
        echo "Загрузка справочника территорий…"
        python manage.py seed_reference
        ;;
esac

echo "Запуск: $*"
exec "$@"
