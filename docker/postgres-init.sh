#!/bin/sh
# =====================================================================================
# Роль приложения в PostgreSQL — без прав суперпользователя.
#
# Выполняется образом postgres один раз, при создании каталога данных. Приложение
# владеет своей базой и больше ничем: запрос, подменённый через уязвимость приложения,
# не прочитает файлы сервера базы и не запустит в нём программу. Суперпользователь
# остаётся для обслуживания изнутри контейнера (локальное соединение без пароля);
# пароль у него снимается, и по сети под ним не войти.
#
# Каталог данных, созданный до появления этого сценария, не меняется: там роль
# приложения остаётся суперпользователем, перевод описан в docs/DEPLOYMENT.md.
#
# Образ выполняет сценарий сам или читает его в свою оболочку — смотря по правам файла,
# поэтому режимы оболочки здесь не меняются; отказ psql прерывает создание базы.
# =====================================================================================

psql -v ON_ERROR_STOP=1 \
    --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" \
    --set=app_user="$APP_DB_USER" \
    --set=app_password="$APP_DB_PASSWORD" \
    --set=database="$POSTGRES_DB" \
    --set=superuser="$POSTGRES_USER" <<'SQL'
CREATE ROLE :"app_user" LOGIN PASSWORD :'app_password';
ALTER DATABASE :"database" OWNER TO :"app_user";
ALTER ROLE :"superuser" PASSWORD NULL;
SQL
